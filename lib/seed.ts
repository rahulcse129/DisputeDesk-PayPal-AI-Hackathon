import type { CaseRecord, Dispute, OrderDetails, TrackingInfo } from "./types";

const DAY = 86_400_000;
const iso = (offsetDays: number, hour = 10) => {
  const d = new Date(Date.now() + offsetDays * DAY);
  d.setUTCHours(hour, 0, 0, 0);
  return d.toISOString();
};
const usd = (value: string) => ({ value, currency: "USD" });

export interface SeedDispute {
  dispute: Dispute;
  order: OrderDetails;
  tracking: TrackingInfo;
}

function dispute(
  d: Omit<Dispute, "messages" | "updateTime" | "status" | "stage"> &
    Partial<Pick<Dispute, "status" | "stage" | "messages">>,
): Dispute {
  return {
    status: "WAITING_FOR_SELLER_RESPONSE",
    stage: "INQUIRY",
    updateTime: d.createTime,
    messages: [{ postedBy: "BUYER", time: d.createTime, content: d.buyerClaim }],
    ...d,
  };
}

